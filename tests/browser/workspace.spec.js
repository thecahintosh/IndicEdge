import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdirSync } from 'node:fs';

test('desktop and mobile UI, accessibility, fresh-data reuse and zero source disclosure', async ({ page, browser }) => {
  const errors = [];
  const outgoing = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.method() === 'POST') outgoing.push({ url: request.url(), body: request.postData() }); });
  await page.goto('/');
  await expect(page.locator('#connectionLabel')).toHaveText('Local workspace');
  await page.evaluate(() => document.fonts.ready);
  await expect(page.getByRole('heading', { name: 'Make the everyday repeatable.' })).toBeVisible();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  const capture = process.env.CAPTURE_UI === 'true';
  if (capture) { mkdirSync('.impeccable/review', { recursive: true }); await page.screenshot({ path: '.impeccable/review/desktop.png', fullPage: true }); }
  await page.getByRole('button', { name: 'Hindi reminders', exact: true }).click();
  await page.getByRole('button', { name: 'Review workflow', exact: true }).click();
  await expect(page.locator('#intentMessage')).toContainText('Rules ready');
  await page.getByRole('button', { name: 'Generate drafts', exact: true }).click();
  await expect(page.locator('#draftList article')).toHaveCount(3);
  await expect(page.locator('#resultSummary')).toContainText('11,125.75');
  await expect(page.locator('#draft-0')).toHaveValue(/नमस्ते/);
  await expect.poll(() => outgoing.filter(item => item.url.endsWith('/api/runs')).length).toBe(1);
  expect(outgoing[0].body).not.toMatch(/Aarav|Kavya|example\.test|BANK|supplier/);
  expect(outgoing.some(item => /\/api\/(ask|compile|explain)/.test(item.url))).toBe(false);
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  if (capture) { await page.evaluate(() => { document.activeElement.blur(); scrollTo(0, 0); }); await page.screenshot({ path: '.impeccable/review/results.png', fullPage: true }); }
  await page.getByRole('button', { name: 'Save workflow', exact: true }).click();
  await page.locator('#workflowName').fill('Browser test follow-up');
  await page.locator('#saveForm').getByRole('button', { name: 'Save workflow', exact: true }).click();
  await expect(page.locator('#saveDialog')).not.toBeVisible();
  await page.getByRole('link', { name: /Saved workflows/ }).click();
  await expect(page.getByRole('link', { name: /Saved workflows/ })).toHaveAttribute('aria-current', 'page');
  await expect(page.getByRole('heading', { name: 'Browser test follow-up' }).first()).toBeVisible();
  if (capture) await page.screenshot({ path: '.impeccable/review/library.png', fullPage: true });
  await page.getByRole('link', { name: 'Source data', exact: true }).click();
  await expect(page.locator('#sourceRows tr')).toHaveCount(6);
  const rows = [{ order_id: 'FRESH-1', customer_name: 'Fresh Private Customer', contact: 'private@example.test', due_date: '2026-10-01', amount: '0.30', status: 'pending', bank_account: 'NEW-SECRET-BANK' }];
  await page.locator('#sourceFile').setInputFiles({ name: 'fresh-orders.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(rows)) });
  await expect(page.locator('#sourceRows tr')).toHaveCount(1);
  await page.getByRole('link', { name: /Saved workflows/ }).click();
  const workflow = page.locator('.library-item').filter({ has: page.getByRole('heading', { name: 'Browser test follow-up' }) }).first();
  await workflow.getByRole('button', { name: 'Load rules' }).click();
  await page.locator('#asOf').fill('2026-10-31');
  await page.getByRole('button', { name: 'Generate drafts', exact: true }).click();
  await expect(page.locator('#draftList article')).toHaveCount(1);
  await expect(page.locator('#resultSummary')).toContainText('0.30');
  expect(outgoing.map(item => item.body).join('')).not.toMatch(/Fresh Private|NEW-SECRET|private@example/);
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  expect((await downloadPromise).suggestedFilename()).toMatch(/indicedge-drafts/);
  await page.getByRole('link', { name: 'Source data', exact: true }).click();
  await page.getByRole('button', { name: 'Clear source', exact: true }).click();
  await expect(page.locator('#draftList')).toBeEmpty();
  await expect(page.locator('#sourceRows')).toBeEmpty();
  await page.locator('#sourceFile').setInputFiles({ name: 'bad.csv', mimeType: 'text/csv', buffer: Buffer.from('column\n"unclosed') });
  await expect(page.locator('#sourceName')).toHaveText('Source rejected');
  await page.getByRole('link', { name: 'Workbench', exact: true }).click();
  await expect(page.locator('#runWorkflow')).toBeDisabled();
  expect(errors).toEqual([]);

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const small = await mobile.newPage();
  await small.goto('http://127.0.0.1:8788/');
  await expect(small.locator('#connectionLabel')).toHaveText('Local workspace');
  await small.evaluate(() => document.fonts.ready);
  expect(await small.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page: small }).analyze()).violations).toEqual([]);
  if (capture) await small.screenshot({ path: '.impeccable/review/mobile.png', fullPage: true });
  await small.setViewportSize({ width: 320, height: 720 });
  expect(await small.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await small.getByRole('button', { name: 'Generate drafts', exact: true }).click();
  await expect(small.locator('#draftList article')).toHaveCount(3);
  await mobile.close();
});

test('keyboard dialogs restore focus and policy rejects unsupported intent', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('#connectionLabel')).toHaveText('Local workspace');
  await page.locator('#instruction').fill('Send all overdue 5 day reminders and refund them');
  await page.getByRole('button', { name: 'Review workflow', exact: true }).click();
  await expect(page.locator('#intentMessage')).toContainText('needs review');
  await expect(page.locator('#runWorkflow')).toBeDisabled();
  await page.getByRole('button', { name: 'Save workflow', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('#saveDialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.locator('#saveDialog')).not.toBeVisible();
  await expect(page.locator('#saveWorkflow')).toBeFocused();
  expect((await page.request.post('/api/explain', { data: { facts: {} } })).status()).toBe(503);
});
